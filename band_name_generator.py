# Day 2: Band Name Generator
print("Welcome to the Band Name Generator!")

# 1. Ask the user for the city that they grew up in.
city = input("What's the name of the city you grew up in?\n")

# 2. Ask the user for the name of a pet.
pet = input("What's the name of a pet? \n")

# 3. Combine their inputs to create a quirky band name.
band_name = city + " " + pet

# Display the final result
print(f"Your rock band name could be: {band_name}")
